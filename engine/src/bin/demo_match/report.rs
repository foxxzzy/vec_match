fn pretty_axis(axis: &str) -> String {
    let mut output = String::new();
    for (index, ch) in axis.chars().enumerate() {
        if index > 0 && ch.is_uppercase() {
            output.push(' ');
        }
        output.push(ch);
    }
    output
}

pub(crate) fn pair_name(spec: &ScenarioSpec) -> String {
    format!("{} + {}", spec.a_name, spec.b_name)
}

